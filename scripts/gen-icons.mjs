// Regenerates src/icons.data.ts: inner markup for the 127 registry icons only (keeps lucide out of the bundle).
import { readFileSync, writeFileSync } from "node:fs";
import { icons } from "lucide";
const src = readFileSync("src/icons.ts", "utf8");
const alias = Object.fromEntries([...src.matchAll(/^\s+(\w+): "(\w+)",$/gm)].map((m) => [m[1], m[2]]));
const names = [...src.match(/ICON_NAMES = \[([\s\S]*?)\] as const/)[1].matchAll(/"(\w+)"/g)].map((m) => m[1]);
const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const out = {};
for (const n of names) {
  const node = icons[alias[n] ?? n[0].toUpperCase() + n.slice(1)];
  if (!node) throw new Error(`Unknown icon: ${n}`);
  out[n] = node.map(([t, a]) => `<${t} ${Object.entries(a).map(([k, v]) => `${k}="${esc(v)}"`).join(" ")}/>`).join("");
}
writeFileSync("src/icons.data.ts", `// Generated by scripts/gen-icons.mjs from lucide (ISC). Do not edit.\nexport const ICON_MARKUP: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${names.length} icons`);
